import uuid
from typing import Optional
from sqlalchemy.orm import Session
from fastapi import HTTPException, status
from backend.app.models.entity import Entity
from backend.app.models.report import Report
from backend.app.models.evidence import Evidence
from backend.app.models.audit import AuditLog
from backend.app.schemas.report import (
    ReportPreviewRequest,
    ReportPreviewResponse,
    ReportCreateRequest,
    ReportResponse
)
from backend.app.security.redaction import redact_sensitive_text, extract_redaction_summary
from backend.app.security.validation import normalize_identifier, generate_stable_entity_id
from backend.app.security.consent import verify_consent_record
from backend.app.services.risk_scoring import calculate_risk_level


def generate_report_preview(request: ReportPreviewRequest) -> ReportPreviewResponse:
    """
    Shows exact information proposed for sharing prior to consent confirmation.
    Redacts sensitive private data from description.
    """
    detected_type, normalized_val = normalize_identifier(request.entity_type, request.raw_identifier)
    redaction_info = extract_redaction_summary(request.description)

    return ReportPreviewResponse(
        proposed_identifier=normalized_val,
        proposed_entity_type=detected_type,
        proposed_scam_type=request.scam_type,
        sanitized_description=redaction_info["sanitized_text"],
        redacted_items_summary=redaction_info["redacted_elements"],
        proposed_destination="SCAMTRACE_INTELLIGENCE",
        proposed_purpose="SCAM_REPORTING",
        proposed_scope="SANITIZED_INDICATORS",
        consent_notice=(
            "By proceeding, you grant explicit consent to share the sanitized threat indicators above "
            "with the ScamTrace Threat Intelligence Network to protect the public. "
            "Sensitive credentials and private PII have been redacted."
        )
    )


def submit_sanitized_report(
    db: Session,
    request: ReportCreateRequest,
    authenticated_user_id: Optional[str] = None
) -> ReportResponse:
    """
    Enforces server-side consent verification and securely submits sanitized report to ScamTrace.
    1. Validates consent record (rejects missing, revoked, or mismatched consent).
    2. If consent was NOT given, logs locally without transmitting to ScamTrace graph.
    3. Redacts unnecessary sensitive data.
    4. Normalizes entity identifier.
    5. Creates or updates Entity.
    6. Creates Report and Evidence records.
    7. Logs audit trail.
    """
    from datetime import datetime
    from backend.app.models.consent import Consent

    # 1. Enforce Server-Side Consent Verification
    if not request.consent_id and not request.consent_given:
        # User explicitly did NOT grant consent for ScamTrace intelligence sharing
        sanitized_desc = redact_sensitive_text(request.description)
        return ReportResponse(
            report_id=f"local_{uuid.uuid4().hex[:12]}",
            entity_id="NOT_TRANSFERRED_NO_CONSENT",
            entity_type="LOCAL_INCIDENT",
            normalized_identifier="RESTRICTED_BY_USER",
            scam_type=request.scam_type or "OTHER_CYBER_FRAUD",
            sanitized_description=sanitized_desc,
            verification_status="LOCAL_ONLY",
            reported_at=datetime.now(),
            message="Incident logged locally in ScamShield. Data was NOT transferred to ScamTrace threat graph as consent was declined."
        )

    # If consent was granted but consent_id was not yet generated by client, create it server-side
    consent_id = request.consent_id
    if not consent_id and request.consent_given:
        auto_consent = Consent(
            consent_id=str(uuid.uuid4()),
            user_id=authenticated_user_id,
            session_id=request.session_id,
            purpose="SCAM_REPORTING",
            destination="SCAMTRACE_INTELLIGENCE",
            data_scope="SANITIZED_INDICATORS",
            consent_version="1.0",
            status="ACTIVE"
        )
        db.add(auto_consent)
        db.flush()
        consent_id = auto_consent.consent_id

    consent = verify_consent_record(
        db=db,
        consent_id=consent_id,
        required_purpose="SCAM_REPORTING",
        required_destination="SCAMTRACE_INTELLIGENCE",
        required_scope="SANITIZED_INDICATORS",
        user_id=authenticated_user_id,
        session_id=request.session_id
    )

    # 2. Normalize Entity
    ent_type, norm_val = normalize_identifier(request.entity_type, request.raw_identifier)
    entity_id = generate_stable_entity_id(ent_type, norm_val)

    # 3. Redact description
    sanitized_desc = redact_sensitive_text(request.description)

    # 4. Check or Create Entity in ScamTrace
    entity = db.query(Entity).filter(Entity.entity_id == entity_id).first()
    if not entity:
        entity = Entity(
            entity_id=entity_id,
            entity_type=ent_type,
            identifier=request.raw_identifier.strip(),
            normalized_value=norm_val,
            risk_score=40.0,  # Base initial risk for reported entity
            risk_level=calculate_risk_level(40.0),
            source_dataset="USER_REPORT",
            evidence_status="REPORTED"
        )
        db.add(entity)
        db.flush()
    else:
        # Increment risk if new report arrives
        new_score = min(100.0, entity.risk_score + 15.0)
        entity.risk_score = new_score
        entity.risk_level = calculate_risk_level(new_score)
        if entity.evidence_status == "UNVERIFIED":
            entity.evidence_status = "REPORTED"

    # 5. Create Report record
    report_id = str(uuid.uuid4())
    report = Report(
        report_id=report_id,
        entity_id=entity.entity_id,
        scam_type=request.scam_type.upper(),
        description=sanitized_desc,
        source="USER_REPORT",
        verification_status="UNVERIFIED"
    )
    db.add(report)
    db.flush()

    # 6. Create Evidence provenance record
    evidence = Evidence(
        evidence_id=str(uuid.uuid4()),
        source_report_id=report.report_id,
        source_dataset="USER_COMMUNITY_REPORT",
        original_field="description",
        extraction_method="CONSENTED_USER_SUBMISSION",
        evidence_status="REPORTED"
    )
    db.add(evidence)

    # 7. Audit log
    audit = AuditLog(
        log_id=str(uuid.uuid4()),
        user_id=authenticated_user_id or request.session_id or "ANONYMOUS",
        action="SUBMIT_REPORT",
        resource=f"entity:{ent_type}:{entity_id[:8]}"
    )
    db.add(audit)

    db.commit()
    db.refresh(report)

    return ReportResponse(
        report_id=report.report_id,
        entity_id=entity.entity_id,
        entity_type=entity.entity_type,
        normalized_identifier=entity.normalized_value,
        scam_type=report.scam_type,
        sanitized_description=report.description,
        verification_status=report.verification_status,
        reported_at=report.reported_at,
        message="Sanitized report securely integrated into ScamTrace threat registry with verified consent."
    )
